// StepResult holds the outcome of a single scenario step.
type StepResult struct {
	Label      string
	Request    *domain.Request
	Response   *domain.Response
	Assertions []domain.AssertionResult
	Extracted  map[string]string // variables extracted from this step's response
	Passed     bool
	Skipped    bool
	Error      string
	// Attempts is how many times the request was sent: 1 normally, more when the step's retry
	// policy re-sent it after a transport error or a 5xx response.
	Attempts int
	// Spec is the result of comparing the response with the scenario's spec.
	Spec SpecCheck
}

// SpecState is the outcome of checking one step's response against the scenario's spec.
type SpecState string

const (
	SpecMatched    SpecState = "matched"
	SpecViolations SpecState = "violations"
	SpecNotChecked SpecState = "not-checked"
)

// SpecCheck records what the spec comparison did for a step. State is empty when the scenario
// has no spec or the step was skipped. Reason explains SpecNotChecked.
type SpecCheck struct {
	State      SpecState
	Reason     string
	Violations []openapi.ValidationError
}

// Result holds the full outcome of running a scenario.
type Result struct {
	Scenario  *domain.Scenario
	Steps     []StepResult
	Passed    bool
	StartedAt time.Time
	Duration  time.Duration

	// Secrets are the resolved values of the environment variables marked secret. Reports
	// replace them wherever they would otherwise be printed.
	Secrets []string
	// RevealExtracted lets reports print extracted values whose names look secret. It is a
	// report-time choice made by the caller (clrsig run --show-extracted); it never reveals
	// the values in Secrets.
	RevealExtracted bool

	// Seed is the seed the scenario's dynamic values came from; UsedRandomness says whether any
	// were random (a run that only reads the clock needs no seed to be replayed).
	Seed           int64
	UsedRandomness bool
	// Variables are the scenario's own variables as they were generated for this run.
	Variables []ResolvedVariable
	// SetupError is set when the scenario could not start because a variable or function in it
	// failed (an unknown function, a bad argument, …); no step was sent.
	SetupError string
}

// ResolvedVariable is a scenario variable and the value it was given for one run.
type ResolvedVariable struct {
	Name   string
	Value  string
	Secret bool
}

// Runner executes scenarios against the HTTP executor.
type Runner struct {
	exec     *executor.Executor
	asserter *assertions.Evaluator
	spec     *openapi.Spec // nil if no spec binding

	engine *variables.Engine // nil: a fresh random seed for every run
	key    string
}

// WithEngine returns a runner whose dynamic values ({{$guid}}, {{$date +7d}}, …) are generated by
// engine, so the run can be replayed with the engine's seed. key names the scenario (for example
// its path) and decides which part of the seeded stream it gets, so the values a scenario
// receives do not depend on the order scenarios run in. An empty key means the scenario's title.
func (r *Runner) WithEngine(engine *variables.Engine, key string) *Runner {
	c := *r
	c.engine, c.key = engine, key
	return &c
}

func New(exec *executor.Executor) *Runner {
	return &Runner{exec: exec, asserter: assertions.New()}
}

// NewWithSpec creates a Runner that automatically validates each step's response
// against the provided OpenAPI spec, and enables operationId-based schema assertions.
func NewWithSpec(exec *executor.Executor, spec *openapi.Spec) *Runner {
	return &Runner{exec: exec, asserter: assertions.NewWithSpec(spec), spec: spec}
}

// Run executes all steps of the scenario sequentially.
func (r *Runner) Run(ctx context.Context, s *domain.Scenario, env *domain.Environment) *Result {
	return r.RunFrom(ctx, s, env, 0)
}

// RunFrom executes the scenario starting from the given step index (0-based).
// Steps before fromStep and disabled steps are recorded as skipped.
func (r *Runner) RunFrom(ctx context.Context, s *domain.Scenario, env *domain.Environment, fromStep int) *Result {
	result := &Result{
		Scenario:  s,
		StartedAt: time.Now(),
		Passed:    true,
		Secrets:   variables.SecretValues(env),
	}

	eng := r.engine
	if eng == nil {
		eng = variables.NewEngine(variables.RandomSeed())
	}
	key := r.key
	if key == "" {
		key = s.Title
	}
	eng = eng.Derive(key)
	resolver := variables.NewResolverWith(env, eng)
	resolver.Define(s.Variables)
	result.Seed = eng.Seed()
	for _, v := range s.Variables {
		val, _ := resolver.Get(v.Name)
		result.Variables = append(result.Variables, ResolvedVariable{Name: v.Name, Value: val, Secret: v.Secret})
		if v.Secret && val != "" {
			result.Secrets = append(result.Secrets, val)
		}
	}
	if errs := resolver.TakeErrors(); len(errs) > 0 {
		msgs := make([]string, len(errs))
		for i, e := range errs {
			msgs[i] = e.Error()
		}
		result.SetupError = strings.Join(msgs, "; ")
		result.Passed = false
		for i := range s.Steps {
			result.Steps = append(result.Steps, StepResult{Label: s.Steps[i].Label, Skipped: true})
		}
		result.UsedRandomness = eng.UsedRandomness()
		result.Duration = time.Since(result.StartedAt)
		return result
	}
	prevFailed := false

	for i := range s.Steps {
		step := &s.Steps[i]
		if i < fromStep || step.Disabled {
			result.Steps = append(result.Steps, StepResult{Label: step.Label, Skipped: true})
			continue
		}
		sr := r.runStep(ctx, step, resolver, prevFailed)
		result.Steps = append(result.Steps, sr)

		if !sr.Passed && !sr.Skipped {
			result.Passed = false
			prevFailed = true
			if step.FailPolicy == domain.FailPolicyStop || step.FailPolicy == "" {
				for j := i + 1; j < len(s.Steps); j++ {
					result.Steps = append(result.Steps, StepResult{
						Label:   s.Steps[j].Label,
						Skipped: true,
					})
				}
				break
			}
		} else {
			prevFailed = false
		}
	}

	result.UsedRandomness = eng.UsedRandomness()
	result.Duration = time.Since(result.StartedAt)
	return result
}

// send executes the request, re-sending it up to retry.MaxAttempts times in total when the
// attempt fails at the transport level or the server answers 5xx. A failed assertion never
// triggers a retry: it would hide a real contract violation. Only the last attempt is evaluated.
func (r *Runner) send(ctx context.Context, req *domain.Request, retry *domain.RetryPolicy) (*domain.Response, int, error) {
	max := 1
	if retry != nil && retry.MaxAttempts > 1 {
		max = retry.MaxAttempts
	}
	for attempt := 1; ; attempt++ {
		resp, err := r.exec.Execute(ctx, req)
		retryable := err != nil || resp.StatusCode >= 500
		if !retryable || attempt >= max || ctx.Err() != nil {
			return resp, attempt, err
		}
		if retry.Delay > 0 {
			select {
			case <-time.After(retry.Delay):
			case <-ctx.Done():
				return resp, attempt, err
			}
		}
	}
}

func (r *Runner) runStep(ctx context.Context, step *domain.ScenarioStep, resolver *variables.Resolver, prevFailed bool) StepResult {
	sr := StepResult{Label: step.Label}

	if prevFailed && step.FailPolicy == domain.FailPolicySkip {
		sr.Skipped = true
		return sr
	}

	if step.Request == nil {
		sr.Error = "step has no request (use inline request or resolve requestRef before running)"
		return sr
	}

	resolved := resolver.InterpolateRequest(step.Request)
	sr.Request = resolved
	if r.spec != nil {
		sr.Spec = SpecCheck{State: SpecNotChecked, Reason: "the step did not complete"}
	}

	// Assertion values use variables and functions too, so a test can check that a response
	// echoes a generated value.
	asserts := make([]domain.Assertion, len(step.Assertions))
	for i, a := range step.Assertions {
		a.Path = resolver.Interpolate(a.Path)
		a.Name = resolver.Interpolate(a.Name)
		if text, ok := a.Expected.(string); ok {
			a.Expected = resolver.Interpolate(text)
		}
		asserts[i] = a
	}
	if errs := resolver.TakeErrors(); len(errs) > 0 {
		msgs := make([]string, len(errs))
		for i, e := range errs {
			msgs[i] = e.Error()
		}
		sr.Error = strings.Join(msgs, "; ")
		return sr
	}
	// A {{name}} nothing gave a value to would go out with its braces in the URL, header or body,
	// so the step is not sent, as an operation is not in clrsig conform.
	if missing := variables.UnresolvedPlaceholders(resolved); len(missing) > 0 {
		refs := make([]string, len(missing))
		for i, n := range missing {
			refs[i] = "{{" + n + "}}"
		}
		sr.Error = "not sent: no value for " + strings.Join(refs, ", ") +
			" (set it in the environment, with --var, in the scenario's variables, or extract it in an earlier step)"
		return sr
	}

	if step.TimeoutMs > 0 {
		resolved.Timeout = time.Duration(step.TimeoutMs) * time.Millisecond
	}
	resp, attempts, err := r.send(ctx, resolved, step.Retry)
	sr.Attempts = attempts
	if err != nil {
		sr.Error = err.Error()
		return sr
	}
	sr.Response = resp

	// Evaluate assertions
	sr.Assertions = r.asserter.EvaluateAll(asserts, resp)
	sr.Passed = true
	for _, ar := range sr.Assertions {
		if !ar.Passed {
			sr.Passed = false
		}
	}

	// Spec conformance validation (when spec is bound and not opted out)
	if r.spec != nil {
		doValidate := true
		if step.ValidateSpec != nil {
			doValidate = *step.ValidateSpec
		}
		path := urlPath(resolved.URL)
		switch {
		case !doValidate:
			sr.Spec = SpecCheck{State: SpecNotChecked, Reason: "spec validation is turned off for this step"}
		case !r.spec.HasOperation(string(resolved.Method), path):
			sr.Spec = SpecCheck{State: SpecNotChecked, Reason: "no matching operation in the spec"}
		default:
			violations := openapi.ValidateResponseByPath(r.spec, string(resolved.Method), path, resp.StatusCode, resp)
			sr.Spec = SpecCheck{State: SpecMatched, Violations: violations}
			if len(violations) > 0 {
				sr.Spec.State = SpecViolations
			}
			for _, v := range violations {
				ar := domain.AssertionResult{
					Assertion: domain.Assertion{Type: domain.AssertionSchema, Name: "spec conformance"},
					Passed:    false,
					Message:   v.Error(),
				}
				sr.Assertions = append(sr.Assertions, ar)
				sr.Passed = false
			}
		}
	}

	// Extract variables (regardless of assertion outcome)
	extracted := make(map[string]string)
	for _, ex := range step.Extractions {
		val, err := extractValue(ex, resp)
		if err != nil {
			// A value the next steps rely on was not found: the step fails, like a failed assertion.
			msg := fmt.Sprintf("extraction %q: %v", ex.Name, err)
			if sr.Error != "" {
				msg = sr.Error + "; " + msg
			}
			sr.Error = msg
			sr.Passed = false
			continue
		}
		extracted[ex.Name] = val
		resolver.Set(ex.Name, val)
	}
	sr.Extracted = extracted

	return sr
}

func extractValue(ex domain.Extraction, resp *domain.Response) (string, error) {
	switch ex.Source {
	case domain.ExtractStatus:
		return fmt.Sprintf("%d", resp.StatusCode), nil

	case domain.ExtractHeader:
		if v, ok := resp.HeaderValue(ex.Path); ok {
			return v, nil
		}
		return "", fmt.Errorf("header %q not found in response", ex.Path)

	case domain.ExtractJSONPath:
		body := resp.BodyString()
		if body == "" {
			return "", fmt.Errorf("response body is empty")
		}
		data, err := assertions.DecodeJSON(body)
		if err != nil {
			return "", fmt.Errorf("response body is not valid JSON: %w", err)
		}
		val, err := jsonpath.Get(ex.Path, data)
		if err != nil {
			return "", fmt.Errorf("jsonpath %q: %w", ex.Path, err)
		}
		return assertions.FormatValue(val), nil

	default:
		return "", fmt.Errorf("unknown extraction source %q", ex.Source)
	}
}

func urlPath(rawURL string) string {
	u, err := url.Parse(rawURL)
	if err != nil {
		return rawURL
	}
	if u.Path == "" {
		return "/"
	}
	return u.Path
}

// AllPassed reports whether every non-skipped step passed all assertions.
func (res *Result) AllPassed() bool {
	return res.Passed
}

// Counts returns (passed, failed, skipped) step counts.
func (res *Result) Counts() (passed, failed, skipped int) {
	for _, s := range res.Steps {
		switch {
		case s.Skipped:
			skipped++
		case s.Passed && s.Error == "":
			passed++
		default:
			failed++
		}
	}
	return
}

// AssertionCounts returns total (passed, failed) assertion counts across all steps.
func (res *Result) AssertionCounts() (passed, failed int) {
	for _, s := range res.Steps {
		for _, a := range s.Assertions {
			if a.Passed {
				passed++
			} else {
				failed++
			}
		}
	}
	return
}
