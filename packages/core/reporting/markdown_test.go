func TestConformMarkdown(t *testing.T) {
	neg := &conformance.NegativeResult{
		SpecTitle: "test-api", SpecVersion: "1.0.0",
		Probes: []conformance.NegativeProbeResult{{Description: "POST /users without auth", StatusCode: 201}},
	}
	md := string(reporting.ConformMarkdown(makeConformResult(true), conformance.ComputeCoverage(makeConformResult(true)), neg))
	for _, want := range []string{"# test-api 1.0.0", "GET /health", "## Coverage", "## Negative conformance probes", "server accepted invalid request with 201", "❌ **FAILED**"} {
		if !strings.Contains(md, want) {
			t.Errorf("missing %q in:\n%s", want, md)
		}
	}
}

func warnOnlyDiff() (*openapi.DiffResult, []openapi.DiffChange) {
	changes := []openapi.DiffChange{
		{ID: "x", Text: "response header changed", Method: "GET", Path: "/users", Level: "WARN"},
		{ID: "y", Text: "endpoint added", Method: "GET", Path: "/ping", Level: "INFO"},
	}
	return &openapi.DiffResult{Changes: changes}, changes
}

func TestDiffThresholdsInEveryFormat(t *testing.T) {
	res, changes := warnOnlyDiff()

	if md := string(reporting.DiffMarkdown(res, changes, openapi.FailOnBreaking)); !strings.Contains(md, "✅ **PASSED**") || !strings.Contains(md, "no breaking changes") {
		t.Errorf("warnings do not fail at the default threshold:\n%s", md)
	}
	md := string(reporting.DiffMarkdown(res, changes, openapi.FailOnWarning))
	if !strings.Contains(md, "❌ **FAILED**") || !strings.Contains(md, `1 at or above "warning"`) {
		t.Errorf("a warning fails at --fail-on warning:\n%s", md)
	}
	if md := string(reporting.DiffMarkdown(res, changes, openapi.FailOnInfo)); !strings.Contains(md, `2 at or above "info"`) {
		t.Errorf("info counts everything:\n%s", md)
	}

	html, err := reporting.DiffHTMLOn(res, changes, openapi.FailOnWarning)
	if s := mustHTML(t, html, err); !strings.Contains(s, `class="verdict bad"`) {
		t.Error("HTML verdict follows the threshold")
	}
	html, err = reporting.DiffHTMLOn(res, changes, openapi.FailOnBreaking)
	if s := mustHTML(t, html, err); !strings.Contains(s, `class="verdict ok"`) {
		t.Error("HTML verdict passes at the default threshold")
	}

	failures := func(on openapi.FailOn) int {
		b, err := reporting.DiffJUnitOn(res, on)
		if err != nil {
			t.Fatal(err)
		}
		var doc struct {
			Failures int `xml:"failures,attr"`
		}
		if err := xml.Unmarshal(b, &doc); err != nil {
			t.Fatal(err)
		}
		return doc.Failures
	}
	if failures(openapi.FailOnBreaking) != 0 || failures(openapi.FailOnWarning) != 1 || failures(openapi.FailOnInfo) != 2 {
		t.Errorf("JUnit failures by threshold = %d/%d/%d", failures(openapi.FailOnBreaking), failures(openapi.FailOnWarning), failures(openapi.FailOnInfo))
	}
}
