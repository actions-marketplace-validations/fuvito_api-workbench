func TestMarkdown_PassedAndFailed(t *testing.T) {
	md := string(reporting.Markdown(passedResult("Lifecycle"), nil))
	for _, want := range []string{"# Lifecycle", "✅ **PASSED**", "- ✅ **PASS** step one", "✓ status eq 200", "Generated by Clear Signal"} {
		if !strings.Contains(md, want) {
			t.Errorf("missing %q in:\n%s", want, md)
		}
	}
	md = string(reporting.Markdown(failedResult("Broken"), nil))
	for _, want := range []string{"❌ **FAILED**", "- ❌ **FAIL** step one", "got 500, want 200"} {
		if !strings.Contains(md, want) {
			t.Errorf("missing %q in:\n%s", want, md)
		}
	}
}

func TestMarkdown_EscapesUntrustedText(t *testing.T) {
	r := failedResult("a|b <script>alert(1)</script> *bold* [x](y)")
	r.Steps[0].Label = "step <img src=x onerror=1> `code`"
	md := string(reporting.Markdown(r, nil))
	unescaped := strings.ReplaceAll(md, `\<`, "")
	for _, raw := range []string{"<script>", "<img", "*bold*", "[x](y)", "`code`"} {
		if strings.Contains(unescaped, raw) {
			t.Errorf("unescaped %q in:\n%s", raw, md)
		}
	}
	if !strings.Contains(md, `\<script\>`) {
		t.Errorf("expected escaped markup:\n%s", md)
	}
}

