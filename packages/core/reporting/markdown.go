package reporting

import (
	"fmt"
	"strings"
	"time"

	"github.com/fuvito/api-workbench/packages/core/conformance"
	"github.com/fuvito/api-workbench/packages/core/openapi"
	"github.com/fuvito/api-workbench/packages/core/scenario"
)

var statusIcon = map[string]string{
	"PASS": "✅", "FAIL": "❌", "ERR": "❌", "SKIP": "⏭️", "WARN": "⚠️", "INFO": "ℹ️",
}

// mdEscape makes untrusted text safe inside Markdown, including HTML-looking text, which GitHub
// would otherwise render.
func mdEscape(s string) string {
	var b strings.Builder
	for _, r := range s {
		switch r {
		case '\\', '`', '*', '_', '[', ']', '<', '>', '|', '#':
			b.WriteByte('\\')
		}
		b.WriteRune(r)
	}
	return strings.ReplaceAll(b.String(), "\n", " ")
}

// renderMarkdown writes the shared report model as Markdown, suitable for pull-request comments
// and the GitHub job summary.
func renderMarkdown(doc htmlDoc) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", mdEscape(doc.Title))
	if doc.Subtitle != "" {
		fmt.Fprintf(&b, "%s\n\n", mdEscape(doc.Subtitle))
	}
	verdict := "✅ **PASSED**"
	if !doc.Passed {
		verdict = "❌ **FAILED**"
	}
	fmt.Fprintf(&b, "%s — %s\n", verdict, mdEscape(doc.Summary))

	for _, sec := range doc.Sections {
		fmt.Fprintf(&b, "\n## %s\n\n", mdEscape(sec.Heading))
		if sec.Note != "" {
			fmt.Fprintf(&b, "%s\n\n", mdEscape(sec.Note))
		}
		for _, row := range sec.Rows {
			icon := statusIcon[row.Status]
			if icon == "" {
				icon = "•"
			}
			line := fmt.Sprintf("- %s **%s** %s", icon, row.Status, mdEscape(row.Title))
			if row.Meta != "" {
				line += " — " + mdEscape(row.Meta)
			}
			b.WriteString(line + "\n")
			for _, l := range row.Lines {
				fmt.Fprintf(&b, "  - %s %s\n", l.Mark, mdEscape(l.Text))
			}
		}
		if sec.Footer != "" {
			fmt.Fprintf(&b, "\n**%s**\n", mdEscape(sec.Footer))
		}
		for _, l := range sec.Lists {
			if len(l.Items) == 0 {
				continue
			}
			fmt.Fprintf(&b, "\n**%s (%d)**\n\n", mdEscape(l.Heading), len(l.Items))
			for _, item := range l.Items {
				fmt.Fprintf(&b, "- `%s`\n", strings.ReplaceAll(item, "`", "'"))
			}
		}
	}
	b.WriteString("\n_Generated by Clear Signal. Extracted variable values are not included in this report._\n")
	return []byte(b.String())
}

// Markdown returns a Markdown report for a scenario run.
func Markdown(result *scenario.Result, cov *openapi.ScenarioCoverageResult) []byte {
	return renderMarkdown(scenarioDoc(result, cov))
}

// MarkdownMulti returns one Markdown report covering several scenarios.
func MarkdownMulti(title string, results []*scenario.Result, total time.Duration, cov ...SpecCoverage) []byte {
	return renderMarkdown(multiDoc(title, results, total, cov...))
}

// ConformMarkdown returns a Markdown report for a conformance run.
func ConformMarkdown(result *conformance.ConformResult, cov *conformance.CoverageReport, neg *conformance.NegativeResult) []byte {
	return renderMarkdown(conformDoc(result, cov, neg))
}

// DiffMarkdown returns a Markdown report for a spec diff; the verdict follows the on threshold.
func DiffMarkdown(result *openapi.DiffResult, changes []openapi.DiffChange, on openapi.FailOn) []byte {
	return renderMarkdown(diffDoc(result, changes, on))
}
