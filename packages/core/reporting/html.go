type htmlLine struct {
	Mark string
	Text string
	OK   bool
}

type htmlRow struct {
	Status string // PASS, FAIL, SKIP, ERR, WARN, INFO
	Title  string
	Meta   string
	Lines  []htmlLine
}

type htmlList struct {
	Heading string
	Items   []string
}

type htmlSection struct {
	Heading string
	Note    string
	Rows    []htmlRow
	Footer  string
	Lists   []htmlList
}

type htmlDoc struct {
	Title    string
	Subtitle string
	Passed   bool
	Summary  string
	Sections []htmlSection
}

