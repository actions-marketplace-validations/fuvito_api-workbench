func renderHTML(doc htmlDoc) ([]byte, error) {
	var buf bytes.Buffer
	if err := htmlTmpl.Execute(&buf, doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func scenarioSummary(result *scenario.Result) string {
	passed, failed, skipped := result.Counts()
	apassed, afailed := result.AssertionCounts()
	return fmt.Sprintf("%d passed, %d failed, %d skipped  (%d/%d assertions passed)  %dms",
		passed, failed, skipped, apassed, apassed+afailed, result.Duration.Milliseconds())
}

func scenarioSection(result *scenario.Result) htmlSection {
	x := redactorFor(result)
	sec := htmlSection{Heading: result.Scenario.Title, Note: result.Scenario.Description}
	for _, v := range result.Variables {
		sec.Rows = append(sec.Rows, htmlRow{Status: "INFO", Title: "variable " + v.Name, Meta: x.variable(v)})
	}
	if result.SetupError != "" {
		sec.Rows = append(sec.Rows, htmlRow{Status: "ERR", Title: "scenario could not start", Lines: []htmlLine{{Mark: "!", Text: x.text(result.SetupError)}}})
	}
	for _, sr := range result.Steps {
		row := htmlRow{Title: sr.Label}
		switch {
		case sr.Skipped:
			row.Status = "SKIP"
		case sr.Error != "" || !sr.Passed:
			row.Status = "FAIL"
		default:
			row.Status = "PASS"
		}
		if sr.Response != nil {
			row.Meta = fmt.Sprintf("%d · %dms", sr.Response.StatusCode, sr.Response.Duration.Milliseconds())
		}
		if sr.Attempts > 1 {
			row.Meta += fmt.Sprintf(" · %d attempts", sr.Attempts)
		}
		if sr.Error != "" {
			row.Lines = append(row.Lines, htmlLine{Mark: "!", Text: "error: " + x.text(sr.Error)})
		}
		for _, ar := range sr.Assertions {
			label := assertionLabel(ar.Assertion)
			if ar.Passed {
				row.Lines = append(row.Lines, htmlLine{Mark: "✓", Text: label, OK: true})
			} else {
				row.Lines = append(row.Lines, htmlLine{Mark: "✗", Text: label + ": " + x.text(ar.Message)})
			}
		}
		for _, name := range sortedKeys(sr.Extracted) {
			row.Lines = append(row.Lines, htmlLine{Mark: "→", Text: name + " extracted", OK: true})
		}
		sec.Rows = append(sec.Rows, row)
	}
	return sec
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func opLines(ops []openapi.CoveredOperation) []string {
	var out []string
	for _, op := range sortedCovOps(ops) {
		out = append(out, op.Method+" "+op.Path)
	}
	return out
}

// HTML returns a self-contained, human-readable HTML report for a scenario run.
// Pass a non-nil cov to append a spec coverage section. Extracted variable values
// are deliberately left out so the file is safe to share as a CI artifact.
func withSeed(summary string, seed int64, used bool) string {
	if !used {
		return summary
	}
	return fmt.Sprintf("%s  ·  seed %d", summary, seed)
}

func scenarioDoc(result *scenario.Result, cov *openapi.ScenarioCoverageResult) htmlDoc {
	doc := htmlDoc{
		Title:    result.Scenario.Title,
		Subtitle: "Scenario run",
		Passed:   result.Passed,
		Summary:  withSeed(scenarioSummary(result), result.Seed, result.UsedRandomness),
		Sections: []htmlSection{scenarioSection(result)},
	}
	if cov != nil {
		doc.Sections = append(doc.Sections, coverageSection("Spec coverage", cov))
	}
	return doc
}

func coverageSection(heading string, cov *openapi.ScenarioCoverageResult) htmlSection {
	return htmlSection{
		Heading: heading,
		Footer:  fmt.Sprintf("%d / %d operations (%.0f%%)", cov.Covered, cov.Total, cov.Percent),
		Lists: []htmlList{
			{Heading: "Covered", Items: opLines(cov.Exercised)},
			{Heading: "Not covered", Items: opLines(cov.Missed)},
		},
	}
}

// HTMLMulti returns one HTML report covering several scenarios, for runs such as a bundle.
func multiDoc(title string, results []*scenario.Result, total time.Duration, cov ...SpecCoverage) htmlDoc {
	passedScenarios, steps, assertsPassed, assertsTotal := 0, 0, 0, 0
	doc := htmlDoc{Title: title, Subtitle: "Several scenarios"}
	for _, r := range results {
		if r.Passed {
			passedScenarios++
		}
		p, f, _ := r.Counts()
		steps += p + f
		ap, af := r.AssertionCounts()
		assertsPassed += ap
		assertsTotal += ap + af
		sec := scenarioSection(r)
		sec.Footer = scenarioSummary(r)
		verdict := "PASSED"
		if !r.Passed {
			verdict = "FAILED"
		}
		sec.Heading = fmt.Sprintf("%s — %s", r.Scenario.Title, verdict)
		doc.Sections = append(doc.Sections, sec)
	}
	for _, c := range cov {
		heading := "Spec coverage"
		if len(cov) > 1 {
			heading += " (" + c.Spec + ")"
		}
		doc.Sections = append(doc.Sections, coverageSection(heading, c.Result))
	}
	doc.Passed = passedScenarios == len(results)
	seed, used := runSeed(results)
	doc.Summary = withSeed(fmt.Sprintf("%d/%d scenarios passed  (%d steps, %d/%d assertions passed)  %dms",
		passedScenarios, len(results), steps, assertsPassed, assertsTotal, total.Milliseconds()), seed, used)
	return doc
}

// ConformHTML returns a self-contained HTML report for a conformance run. Pass non-nil
// coverage and/or neg to append the coverage summary and the negative-probe results.
func conformDoc(result *conformance.ConformResult, cov *conformance.CoverageReport, neg *conformance.NegativeResult) htmlDoc {
	passed, failed, skipped := result.Counts()
	doc := htmlDoc{
		Title:    fmt.Sprintf("%s %s", result.SpecTitle, result.SpecVersion),
		Subtitle: "Conformance run against " + result.BaseURL,
		Summary: fmt.Sprintf("%d operations  ·  %d passed  ·  %d failed  ·  %d skipped  %dms",
			passed+failed+skipped, passed, failed, skipped, result.Duration.Milliseconds()),
	}
	doc.Passed = failed == 0

	x := newRedactor(result.Secrets, false)
	doc.Subtitle = x.text(doc.Subtitle)
	ops := htmlSection{Heading: "Operations"}
	if n, missing := result.BlockedSummary(); n > 0 {
		ops.Footer = x.text(conformance.MissingValuesAdvice(n, missing))
	}
	for _, op := range result.Operations {
		row := htmlRow{Title: op.Method + " " + op.Path}
		switch {
		case op.Skipped:
			row.Status = "SKIP"
		case op.Error != "" || !op.Passed():
			row.Status = "FAIL"
		default:
			row.Status = "PASS"
		}
		if op.StatusCode > 0 {
			row.Meta = fmt.Sprintf("%d · %dms", op.StatusCode, op.DurationMs)
		}
		if op.Error != "" {
			row.Lines = append(row.Lines, htmlLine{Mark: "!", Text: "error: " + x.text(op.Error)})
		}
		if op.Blocked != "" {
			row.Lines = append(row.Lines, htmlLine{Mark: "✗", Text: x.text(op.Blocked)})
		}
		for _, v := range op.RequestViolations {
			row.Lines = append(row.Lines, htmlLine{Mark: "✗", Text: "request: " + x.text(v.Error())})
		}
		for _, v := range op.Violations {
			row.Lines = append(row.Lines, htmlLine{Mark: "✗", Text: x.text(v.Error())})
		}
		for _, f := range explain(op, x) {
			row.Lines = append(row.Lines, htmlLine{Mark: "→", Text: explanationLine(f)})
		}
		ops.Rows = append(ops.Rows, row)
	}
	doc.Sections = append(doc.Sections, ops)

	if cov != nil {
		sec := htmlSection{
			Heading: "Coverage",
			Footer:  fmt.Sprintf("%d / %d operations (%.0f%%)", cov.Covered, cov.Total, cov.Percent),
		}
		var covered, missed []string
		for _, op := range cov.CoveredOps {
			covered = append(covered, op.Method+" "+op.Path)
		}
		for _, op := range cov.NotCoveredOps {
			missed = append(missed, op.Method+" "+op.Path)
		}
		sec.Lists = []htmlList{{Heading: "Covered", Items: covered}, {Heading: "Not covered", Items: missed}}
		doc.Sections = append(doc.Sections, sec)
	}

	if neg != nil {
		np, nf, ns, ne := neg.Counts()
		sec := htmlSection{
			Heading: "Negative conformance probes",
			Footer: fmt.Sprintf("%d probes  ·  %d passed  ·  %d failed  ·  %d skipped  ·  %d errors  %dms",
				np+nf+ne, np, nf, ns, ne, neg.Duration.Milliseconds()),
		}
		for _, p := range neg.Probes {
			row := htmlRow{Title: p.Description}
			switch {
			case p.Skipped:
				row.Status = "SKIP"
			case p.Error != "":
				row.Status = "ERR"
				row.Lines = append(row.Lines, htmlLine{Mark: "!", Text: "error: " + newRedactor(neg.Secrets, false).text(p.Error)})
			case p.Passed():
				row.Status = "PASS"
				row.Meta = fmt.Sprintf("%d · %dms", p.StatusCode, p.DurationMs)
			default:
				row.Status = "FAIL"
				row.Lines = append(row.Lines, htmlLine{Mark: "✗", Text: fmt.Sprintf("server accepted invalid request with %d", p.StatusCode)})
			}
			sec.Rows = append(sec.Rows, row)
		}
		doc.Sections = append(doc.Sections, sec)
		if nf > 0 {
			doc.Passed = false
		}
	}
	return doc
}

// HTML returns a self-contained, human-readable HTML report for a scenario run.
// Pass a non-nil cov to append a spec coverage section. Extracted variable values are
// deliberately left out so the file is safe to share as a CI artifact.
func HTML(result *scenario.Result, cov *openapi.ScenarioCoverageResult) ([]byte, error) {
	return renderHTML(scenarioDoc(result, cov))
}

// HTMLMulti returns one HTML report covering several scenarios, for runs such as a bundle or
// a folder.
func HTMLMulti(title string, results []*scenario.Result, total time.Duration, cov ...SpecCoverage) ([]byte, error) {
	return renderHTML(multiDoc(title, results, total, cov...))
}

// ConformHTML returns a self-contained HTML report for a conformance run. Pass non-nil
// coverage and/or neg to append the coverage summary and the negative-probe results.
func ConformHTML(result *conformance.ConformResult, cov *conformance.CoverageReport, neg *conformance.NegativeResult) ([]byte, error) {
	return renderHTML(conformDoc(result, cov, neg))
}

// diffDoc builds the document for a spec diff. changes is the list to show (the caller may have
// filtered it); the verdict follows the on threshold.
func diffDoc(result *openapi.DiffResult, changes []openapi.DiffChange, on openapi.FailOn) htmlDoc {
	breaking := 0
	failing := 0
	sec := htmlSection{Heading: "Changes"}
	for _, c := range changes {
		if c.Breaking {
			breaking++
		}
		if c.Fails(on) {
			failing++
		}
		row := htmlRow{Status: c.Level, Title: c.Text}
		if c.Method != "" && c.Path != "" {
			row.Meta = c.Method + " " + c.Path
		}
		sec.Rows = append(sec.Rows, row)
	}
	doc := htmlDoc{
		Title:    "API Spec Diff",
		Subtitle: "Breaking and non-breaking changes between two OpenAPI specs",
		Passed:   !result.Fails(on),
		Sections: []htmlSection{sec},
	}
	switch {
	case len(changes) == 0:
		doc.Summary = "No changes."
	case on != openapi.FailOnBreaking && on != "":
		doc.Summary = fmt.Sprintf("%d change(s)  ·  %d breaking  ·  %d at or above %q", len(changes), breaking, failing, string(on))
	case result.HasBreaking:
		doc.Summary = fmt.Sprintf("%d change(s)  ·  %d breaking", len(changes), breaking)
	default:
		doc.Summary = fmt.Sprintf("%d change(s)  ·  no breaking changes", len(changes))
	}
	return doc
}

// DiffHTML returns a self-contained HTML report for a spec diff, failing on breaking changes.
func DiffHTML(result *openapi.DiffResult, changes []openapi.DiffChange) ([]byte, error) {
	return renderHTML(diffDoc(result, changes, openapi.FailOnBreaking))
}

// DiffHTMLOn is DiffHTML with a chosen --fail-on threshold.
func DiffHTMLOn(result *openapi.DiffResult, changes []openapi.DiffChange, on openapi.FailOn) ([]byte, error) {
	return renderHTML(diffDoc(result, changes, on))
}
